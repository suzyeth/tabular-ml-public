"""Reproduce every number in the README with one command:  python run.py

Writes markdown/CSV tables to results/ and prints the headline table.
`--quick` uses 30 boosting rounds (for smoke tests / CI), not the reported setup.
"""
from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import pandas as pd

from facies_cv.analysis import confusion, error_summary, feature_importance, per_class, per_well
from facies_cv.config import BASE_FEATURES, PROJECT_ROOT, TARGET
from facies_cv.data import load_clean, summarise
from facies_cv.evaluate import leak_probe, pivot_gap, run_grid
from facies_cv.features import add_window_features
from facies_cv.models import model_factories

METRICS = ["accuracy", "macro_f1", "adjacent_accuracy", "fold_acc_min", "fold_acc_max"]


def run(out_dir: Path, n_estimators: int = 300) -> dict:
    df = load_clean()
    df, window_cols = add_window_features(df)
    feature_sets = {"base": BASE_FEATURES, "base+window": BASE_FEATURES + window_cols}

    results, raw = run_grid(
        df, feature_sets, model_factories(n_estimators),
        skip={("base+window", "majority")},
    )
    y = df[TARGET].to_numpy()
    main = raw[("base", "lightgbm", "group")]
    linear = raw[("base", "logistic", "group")]

    outputs = {
        "summary": summarise(df),
        "results": results,
        "gap_macro_f1": pivot_gap(results, "macro_f1"),
        "gap_accuracy": pivot_gap(results, "accuracy"),
        "leak_probe": leak_probe(df),
        "importance": feature_importance(df, BASE_FEATURES, main),
        "per_well": per_well(df, {"lightgbm": main.oof_pred, "logistic": linear.oof_pred}),
        "per_class": per_class(y, main.oof_pred),
        "confusion": confusion(y, main.oof_pred),
        "errors": error_summary(y, main.oof_pred),
    }
    write(outputs, out_dir)
    return outputs


def write(outputs: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    md = ["# Results (generated by `python run.py` — do not edit by hand)\n"]
    for name, obj in outputs.items():
        if isinstance(obj, pd.DataFrame):
            obj.to_csv(out_dir / f"{name}.csv", index=name == "confusion")
            md += [f"## {name}\n", obj.to_markdown(index=name == "confusion", floatfmt=".3f"), ""]
        else:
            md += [f"## {name}\n", "```json", json.dumps(obj, indent=2), "```", ""]
    (out_dir / "results.md").write_text("\n".join(md), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / "results")
    parser.add_argument("--quick", action="store_true", help="30 trees; for smoke tests only")
    args = parser.parse_args()

    start = time.time()
    outputs = run(args.out, n_estimators=30 if args.quick else 300)
    pd.set_option("display.width", 140)
    print("Data:", json.dumps(outputs["summary"]))
    print("\nOut-of-fold scores (kfold = shuffled K-fold, group = leave-one-well-out):")
    print(outputs["results"][["features", "model", "cv", *METRICS]].round(3).to_string(index=False))
    print("\nInflation of macro-F1 caused by random K-fold:")
    print(outputs["gap_macro_f1"].round(3).to_string(index=False))
    print("\nLeak probe (copy the nearest training row in the same well):")
    print(outputs["leak_probe"].round(3).to_string(index=False))
    print(f"\nWrote tables to {args.out}  ({time.time() - start:.0f}s)")


if __name__ == "__main__":
    main()
